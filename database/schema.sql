
CREATE TABLE IF NOT EXISTS public.donation_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    donation_id UUID NOT NULL
        REFERENCES public.donations(id)
        ON DELETE CASCADE,

    requester_name TEXT NOT NULL
        CHECK (
            char_length(trim(requester_name)) BETWEEN 2 AND 100
        ),

    requester_contact TEXT NOT NULL
        CHECK (
            char_length(trim(requester_contact)) BETWEEN 3 AND 100
        ),

    message TEXT DEFAULT ''
        CHECK (
            char_length(message) <= 500
        ),

    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (
            status IN ('pending', 'accepted', 'rejected', 'completed')
        ),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS requests_donation_id_idx
    ON public.donation_requests(donation_id);
    
ALTER TABLE public.donations
ADD COLUMN IF NOT EXISTS pickup_location TEXT NOT NULL DEFAULT '';
