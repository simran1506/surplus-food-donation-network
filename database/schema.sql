-- Surplus Food Donation Network database setup
-- Run the complete script in Supabase Dashboard -> SQL Editor -> New query.
-- The names below exactly match the Express API field names.

create table if not exists public.donations (
  id bigint generated by default as identity primary key,
  donor_name text not null,
  donor_contact text not null,
  food_name text not null,
  quantity text not null,
  food_type text not null check (food_type in ('cooked', 'uncooked', 'packaged', 'produce', 'other')),
  description text not null default '',
  pickup_location text not null,
  expiry_time timestamptz null,
  status text not null default 'available' check (status in ('available', 'claimed', 'completed')),
  created_at timestamptz not null default now()
);

create index if not exists donations_status_created_at_idx
  on public.donations (status, created_at desc);

-- This starter project accesses the database through the Express server using
-- the service-role key. Keep that key ONLY in backend .env; never put it in frontend files.
